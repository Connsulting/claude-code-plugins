"""Injection precision contract (Stream C / AC3).

Two independent defects share this file because they share one entry point.

1. Thresholds must be CONFIG-DRIVEN. Asserted behaviourally: the same corpus and
   the same query, driven with two different `peekHighConfidenceThreshold`
   values, must return different sets of learnings. A grep for the key name
   would pass against a hardcoded fallback; this cannot.

2. The cross-scope injection path must be CLOSED. This is a measured client-data
   leak, not a hypothetical: `db.search` filters repo scope on the bare
   directory NAME, and `repo='platform'` currently holds 220 inbound-square rows
   alongside 56 curietech rows -- two different clients. Working in one client's
   `platform` repo injects the other client's learnings.

The scope test runs end to end through `search-learnings.py --peek` as a real
subprocess, because the leak spans the hierarchy walk (which produces the scope
identity) and the SQL filter (which consumes it); testing either half alone
would miss a mismatch between them.
"""

import importlib.util
import json
import math
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest

PLUGIN_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PLUGIN_ROOT))

import lib.db as db  # noqa: E402


def _load_search():
    spec = importlib.util.spec_from_file_location(
        "search_learnings", PLUGIN_ROOT / "scripts" / "search-learnings.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


sl = _load_search()

SEARCH_SCRIPT = PLUGIN_ROOT / "scripts" / "search-learnings.py"
AUTO_PEEK_HOOK = PLUGIN_ROOT / "hooks" / "auto-peek.sh"

EMBED_DIM = 384


# --- harness ----------------------------------------------------------------


@pytest.fixture()
def peek_env(isolated_db, tmp_path, monkeypatch):
    """Isolated DB exported to every code path that calls load_config() itself.

    The shipped `.claude-plugin/config.json` points dbPath at the live corpus, so
    the assertion below is a hard gate against these tests touching real data.
    `COMPOUND_LEARNING_PINNED_MD` is aimed at a path that does not exist so the
    real pinned.md cannot silently exclude a fixture learning.
    """
    config, conn = isolated_db
    monkeypatch.setenv("SQLITE_DB_PATH", config["sqlite"]["dbPath"])
    monkeypatch.setenv("LEARNINGS_GLOBAL_DIR", str(tmp_path / "learnings"))
    monkeypatch.setenv("COMPOUND_LEARNING_PINNED_MD", str(tmp_path / "absent-pinned.md"))

    resolved = db.load_config()
    assert resolved["sqlite"]["dbPath"].startswith(str(tmp_path)), (
        "refusing to run: the resolved dbPath is not inside tmp_path"
    )
    return config, conn


def _index(conn, doc_id, path, content, scope="global", repo=""):
    db.upsert_document(
        conn, doc_id, content,
        {
            "scope": scope,
            "repo": repo,
            "file_path": str(path),
            "topic": "other",
            "keywords": "",
            "created_at": datetime.now(timezone.utc).isoformat(),
        },
    )


def _search(capsys, query, cwd, *, peek=True, max_results=5,
            threshold=None, peek_threshold=None):
    sl.search_learnings(
        query, cwd,
        max_results=max_results,
        peek_mode=peek,
        threshold_override=threshold,
        peek_threshold_override=peek_threshold,
    )
    out = capsys.readouterr().out
    return json.loads(out)


def _peek_ids(payload):
    return {item["id"] for item in payload.get("learnings", [])}


def _all_results(payload):
    return payload.get("high_confidence", []) + payload.get("possibly_relevant", [])


CACHE_DOC = """# Redis pipeline flush drops the last command on reconnect

**Type:** gotcha
**Topic:** caching

## Problem
A redis pipeline flush issued while the connection is re-establishing silently
drops the final queued command, so the cache write is lost without any error.

## Solution
Await the reconnect before flushing the pipeline.
"""

QUEUE_DOC = """# SQS visibility timeout shorter than the handler duplicates work

**Type:** gotcha
**Topic:** messaging

## Problem
When the SQS visibility timeout is shorter than the worst-case handler runtime,
the message becomes visible again and a second consumer starts the same job.

## Solution
Set the visibility timeout from the measured p99 handler duration.
"""

BUILD_DOC = """# Docker layer cache misses on a changed lockfile ordering

**Type:** gotcha
**Topic:** build

## Problem
A lockfile regenerated with a different key ordering changes the layer hash and
invalidates every downstream docker build layer even though nothing installed.

## Solution
Commit lockfiles regenerated by one tool version only.
"""


# --- AC3, first half: config-driven thresholds ------------------------------


def _plugin_root_with_config(tmp_path, name, learnings_config):
    root = tmp_path / name
    (root / ".claude-plugin").mkdir(parents=True)
    (root / ".claude-plugin" / "config.json").write_text(
        json.dumps({"learnings": learnings_config}), encoding="utf-8"
    )
    return root


def test_peek_threshold_read_from_config_not_hardcoded(peek_env, tmp_path, monkeypatch, capsys) -> None:
    """Two config values, one corpus, one query -> different result sets.

    The peek ceiling is the single knob controlling injection volume, so a
    hardcoded fallback would make every future tuning pass a no-op that still
    reads as configured. Only a behavioural difference proves the config value
    reached the gate.
    """
    _config, conn = peek_env
    learnings = tmp_path / "learnings"
    learnings.mkdir(exist_ok=True)
    for doc_id, body in (("cache", CACHE_DOC), ("queue", QUEUE_DOC), ("build", BUILD_DOC)):
        path = learnings / f"{doc_id}-2026-07-01.md"
        path.write_text(body, encoding="utf-8")
        _index(conn, doc_id, path, body)

    query = "redis pipeline flush reconnect"

    permissive_root = _plugin_root_with_config(
        tmp_path, "cfg-permissive", {"peekHighConfidenceThreshold": 0.99}
    )
    monkeypatch.setenv("CLAUDE_PLUGIN_ROOT", str(permissive_root))
    permissive = _peek_ids(_search(capsys, query, str(tmp_path)))

    strict_root = _plugin_root_with_config(
        tmp_path, "cfg-strict", {"peekHighConfidenceThreshold": 0.01}
    )
    monkeypatch.setenv("CLAUDE_PLUGIN_ROOT", str(strict_root))
    strict = _peek_ids(_search(capsys, query, str(tmp_path)))

    assert permissive, "the permissive threshold must return at least one learning"
    assert strict < permissive, (
        "tightening peekHighConfidenceThreshold in config must shrink the result "
        f"set; got permissive={sorted(permissive)} strict={sorted(strict)}"
    )


def test_peek_still_gates_on_original_distance(peek_env, tmp_path, capsys) -> None:
    """The keyword/FTS boost must never promote a weak semantic match.

    Built with a hand-placed embedding so the raw distance is known: the
    document carries every query keyword, so the rerank drives its adjusted
    distance far below the raw one. A ceiling set between the two must exclude
    it. If the gate ever moves to the reranked distance, the strict run below
    starts including it and this fails.
    """
    _config, conn = peek_env
    query = "widget calibration drift"

    doc = (
        "# Widget calibration drift under thermal load\n\n"
        "**Type:** gotcha\n\n"
        "## Problem\nwidget calibration drift appears only after the enclosure "
        "warms up.\n\n## Solution\nRecalibrate at operating temperature.\n"
    )
    path = tmp_path / "widget-calibration-drift-2026-07-01.md"
    path.write_text(doc, encoding="utf-8")

    import struct

    q = db.get_embedding(query)
    # An arbitrary unit vector orthogonal to q, then a doc vector at cosine 0.6.
    axis = min(range(EMBED_DIM), key=lambda i: abs(q[i]))
    proj = q[axis]
    o = [-proj * q[i] for i in range(EMBED_DIM)]
    o[axis] += 1.0
    norm = math.sqrt(sum(v * v for v in o))
    o = [v / norm for v in o]
    cosine = 0.6
    scale = math.sqrt(1.0 - cosine * cosine)
    vec = [cosine * q[i] + scale * o[i] for i in range(EMBED_DIM)]

    conn.execute(
        "INSERT INTO learnings "
        "(id, content, scope, repo, file_path, topic, keywords, created_at) "
        "VALUES ('widget', ?, 'global', '', ?, 'other', '', ?)",
        (doc, str(path), datetime.now(timezone.utc).isoformat()),
    )
    conn.execute(
        "INSERT INTO vec_learnings (id, embedding) VALUES ('widget', ?)",
        (struct.pack(f"{EMBED_DIM}f", *vec),),
    )
    conn.execute("INSERT INTO fts_learnings (id, content) VALUES ('widget', ?)", (doc,))
    conn.commit()

    # Read the raw distance the engine actually computes, so the test does not
    # depend on which distance metric the vec0 table was declared with.
    plain = _search(capsys, query, str(tmp_path), peek=False, threshold=0.99)
    observed = {r["id"]: r for r in _all_results(plain)}
    assert "widget" in observed, f"fixture document was not retrieved at all: {plain}"
    raw = observed["widget"]["original_distance"]
    reranked = observed["widget"]["distance"]
    assert 0.1 < raw < 0.9, f"fixture distance {raw} is outside the useful range"
    assert reranked < raw - 0.05, (
        f"fixture must be boosted by the rerank to be meaningful: raw={raw} reranked={reranked}"
    )

    permissive = _peek_ids(_search(capsys, query, str(tmp_path), peek_threshold=raw + 0.05))
    strict = _peek_ids(_search(capsys, query, str(tmp_path), peek_threshold=raw - 0.05))

    assert "widget" in permissive, "a raw distance under the ceiling must be injected"
    assert "widget" not in strict, (
        f"raw distance {raw} exceeds the ceiling {raw - 0.05} and must be excluded, "
        f"even though the reranked distance {reranked} would pass"
    )


def test_pinned_sources_loaded_from_shared_helper(peek_env, tmp_path, monkeypatch, capsys) -> None:
    """Pinned entries stay out of peek after load_pinned_sources moves to lib.db.

    They are already resident via pinned.md, so re-injecting them is the
    double-injection feedback loop. Behavioural: point the loader at a fixture
    listing one basename and assert only that learning disappears.
    """
    _config, conn = peek_env
    learnings = tmp_path / "learnings"
    learnings.mkdir(exist_ok=True)

    cache_path = learnings / "redis-pipeline-flush-2026-07-01.md"
    cache_path.write_text(CACHE_DOC, encoding="utf-8")
    _index(conn, "cache", cache_path, CACHE_DOC)

    variant = CACHE_DOC.replace("redis pipeline flush", "redis pipeline flush call")
    variant_path = learnings / "redis-pipeline-reconnect-2026-07-02.md"
    variant_path.write_text(variant, encoding="utf-8")
    _index(conn, "variant", variant_path, variant)

    query = "redis pipeline flush reconnect"
    before = _peek_ids(_search(capsys, query, str(tmp_path), threshold=0.9, peek_threshold=0.9))
    assert {"cache", "variant"} <= before, f"both fixtures must be injectable first: {before}"

    pinned_md = tmp_path / "pinned-fixture.md"
    pinned_md.write_text(f"_source: {cache_path.name}_\n", encoding="utf-8")
    monkeypatch.setenv("COMPOUND_LEARNING_PINNED_MD", str(pinned_md))

    after = _peek_ids(_search(capsys, query, str(tmp_path), threshold=0.9, peek_threshold=0.9))

    assert "cache" not in after, "a pinned learning must not be injected a second time"
    assert "variant" in after, "excluding a pinned entry must not cost the other results"


# --- AC3, second half: the cross-scope leak ---------------------------------

RUNBOOK_A = """# Zephyrine deploy runbook for the payments cutover

**Type:** pattern
**Topic:** deployment

## Problem
The zephyrine deploy runbook has to be replayed by hand for every payments
cutover because the pipeline cannot drain the queue on its own.

## Solution
Drain, cut over, then re-enable the consumer.
"""

RUNBOOK_B = """# Zephyrine deploy runbook for the billing cutover

**Type:** pattern
**Topic:** deployment

## Problem
The zephyrine deploy runbook is replayed manually for each billing cutover
because the pipeline will not drain the queue by itself.

## Solution
Drain, cut over, then re-enable the consumer.
"""


def test_cross_scope_repo_learning_not_injected(peek_env, tmp_path) -> None:
    """Two repos named `platform` under different roots must not share learnings.

    This is the security boundary. Both fixtures match the query equally well
    and both carry `repo='platform'`, so the ONLY thing that can keep the second
    client's learning out of the first client's session is path-identity scope.

    Fails today: the filter matches on the bare directory name, so both rows
    come back.
    """
    config, conn = peek_env
    root_a = (tmp_path / "clientA" / "platform").resolve()
    root_b = (tmp_path / "clientB" / "platform").resolve()
    for root in (root_a, root_b):
        (root / ".projects" / "learnings").mkdir(parents=True)

    file_a = root_a / ".projects" / "learnings" / "zephyrine-deploy-runbook-2026-07-01.md"
    file_b = root_b / ".projects" / "learnings" / "zephyrine-deploy-runbook-2026-07-02.md"
    file_a.write_text(RUNBOOK_A, encoding="utf-8")
    file_b.write_text(RUNBOOK_B, encoding="utf-8")

    # Written exactly as the production writer does: repo is the bare basename
    # and repo_root is never supplied by the writer.
    _index(conn, "runbook-a", file_a, RUNBOOK_A, scope="repo", repo="platform")
    _index(conn, "runbook-b", file_b, RUNBOOK_B, scope="repo", repo="platform")
    conn.commit()

    env = {
        **os.environ,
        "SQLITE_DB_PATH": config["sqlite"]["dbPath"],
        "LEARNINGS_GLOBAL_DIR": str(tmp_path / "learnings"),
        "COMPOUND_LEARNING_PINNED_MD": str(tmp_path / "absent-pinned.md"),
        "CLAUDE_PLUGIN_ROOT": str(PLUGIN_ROOT),
        "HF_HUB_OFFLINE": "1",
    }

    result = subprocess.run(
        [
            sys.executable, str(SEARCH_SCRIPT),
            "--peek",
            "--max-results", "5",
            "--threshold", "0.9",
            "--peek-threshold", "0.9",
            "zephyrine deploy runbook cutover",
            str(root_a),
        ],
        text=True, capture_output=True, env=env, check=False,
    )

    assert result.returncode == 0, result.stderr
    payload = json.loads(result.stdout)
    paths = [
        (item.get("metadata") or {}).get("file_path", "")
        for item in payload.get("learnings", [])
    ]

    assert any(p.startswith(str(root_a)) for p in paths), (
        f"the session's own repo learning must still be injected; got {paths}"
    )
    assert not any(p.startswith(str(root_b)) for p in paths), (
        f"another client's repo learning leaked into this session: {paths}"
    )


# --- the per-session injection cap ------------------------------------------


def _write_peek_transcript(path: Path) -> None:
    entries = [
        {"type": "user", "message": {"content": "How do I drain the deploy queue safely?"}},
        {"type": "assistant", "message": {"content": [
            {"type": "text", "text": "Drain the consumer before the cutover."}
        ]}},
        {"type": "user", "message": {"content": "And what about the visibility timeout?"}},
    ]
    path.write_text(
        "".join(json.dumps(e) + "\n" for e in entries), encoding="utf-8"
    )


def _run_auto_peek(tmp_path, session_name, seen_ids, cap):
    """Drive hooks/auto-peek.sh with a sentinel on the keyword-extraction engine."""
    home = tmp_path / session_name / "home"
    sessions = home / ".claude" / "plugins" / "compound-learning" / "sessions"
    sessions.mkdir(parents=True)

    transcript = tmp_path / session_name / "abcd-1234.jsonl"
    _write_peek_transcript(transcript)
    (sessions / "abcd-1234.seen").write_text(
        "".join(f"seen-id-{i}\n" for i in range(seen_ids)), encoding="utf-8"
    )

    bin_dir = tmp_path / session_name / "bin"
    bin_dir.mkdir()
    keyword_sentinel = tmp_path / session_name / "keyword-engine-was-called"

    claude_stub = bin_dir / "claude"
    claude_stub.write_text(
        """#!/bin/sh
: > "$KEYWORD_SENTINEL"
printf '%s\\n' '{"result":"{\\"keywords\\": [\\"deploy queue\\"]}"}'
""",
        encoding="utf-8",
    )
    claude_stub.chmod(0o755)

    python_stub = bin_dir / "python3"
    python_stub.write_text(
        """#!/bin/sh
case "$1" in
  */extract-transcript-context.py)
    exit 0
    ;;
  */search-learnings.py)
    printf '%s\\n' '{"status":"empty","keywords_searched":[]}'
    exit 0
    ;;
esac
printf 'unexpected python3 call: %s\\n' "$*" >&2
exit 2
""",
        encoding="utf-8",
    )
    python_stub.chmod(0o755)

    env = {
        **os.environ,
        "HOME": str(home),
        "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}",
        "CLAUDE_PLUGIN_ROOT": str(PLUGIN_ROOT),
        "KEYWORD_SENTINEL": str(keyword_sentinel),
        "COMPOUND_LEARNING_MAX_PER_SESSION": str(cap),
    }
    env.pop("CLAUDE_SUBPROCESS", None)
    env.pop("COMPOUND_LEARNING_KEYWORD_ENGINE", None)

    hook_input = {
        "prompt": "How should I handle the deploy queue drain before cutover?",
        "transcript_path": str(transcript),
        "session_id": "abcd-1234",
        "cwd": str(tmp_path),
    }

    result = subprocess.run(
        ["bash", str(AUTO_PEEK_HOOK)],
        input=json.dumps(hook_input),
        text=True, capture_output=True, env=env, check=False,
    )
    return result, keyword_sentinel


def test_session_cap_suppresses_further_injection(tmp_path) -> None:
    """At the cap, auto-peek must stop before the keyword-extraction subprocess.

    Gating after extraction would still pay the per-fire model cost for a result
    that is thrown away, which is the same reasoning the daily cap in
    extract-learnings.sh already uses. The under-cap run is the positive control
    proving the harness reaches that call at all.
    """
    at_cap, at_cap_sentinel = _run_auto_peek(tmp_path, "at-cap", seen_ids=12, cap=12)
    assert at_cap.returncode == 0, at_cap.stderr
    assert not at_cap_sentinel.exists(), (
        "with 12 learnings already injected and a cap of 12, the keyword engine "
        "must not be invoked at all"
    )

    under_cap, under_cap_sentinel = _run_auto_peek(tmp_path, "under-cap", seen_ids=2, cap=12)
    assert under_cap.returncode == 0, under_cap.stderr
    assert under_cap_sentinel.exists(), (
        "under the cap the hook must still run normally"
    )
